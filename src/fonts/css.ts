import type { FontFile, FontManifest, FontWeight } from "./types.js";

function cssString(value: string): string {
  return `"${value.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\r?\n/g, "\\a ")}"`;
}

function encodeAssetUrl(relativePath: string): string {
  return `/${relativePath
    .split("/")
    .map((segment) => encodeURIComponent(segment))
    .join("/")}`;
}

function cssWeight(weight: FontWeight): string {
  return typeof weight === "number" ? String(weight) : `${weight.min} ${weight.max}`;
}

function cssFormat(file: FontFile): string {
  if (file.format === "woff2") {
    return typeof file.weight === "number" ? "woff2" : "woff2-variations";
  }
  if (file.format === "woff") {
    return "woff";
  }
  if (file.format === "ttf") {
    return "truetype";
  }
  return "opentype";
}

/** Renders the project font manifest as the deterministic @font-face sheet. */
export function renderFontCss(manifest: FontManifest | undefined): string {
  if (manifest === undefined || manifest.fonts.length === 0) {
    return "/* No project fonts are installed. */\n";
  }

  const blocks: string[] = ["/* Generated by Frameyard from frameyard.fonts.json. */"];
  for (const font of manifest.fonts) {
    for (const file of font.files) {
      const lines = [
        "@font-face {",
        `  font-family: ${cssString(font.family)};`,
        `  font-style: ${file.style};`,
        "  font-display: block;",
        `  font-weight: ${cssWeight(file.weight)};`,
        `  src: url(${cssString(encodeAssetUrl(file.path))}) format(${cssString(cssFormat(file))});`,
      ];
      if (file.unicodeRange !== undefined) {
        lines.push(`  unicode-range: ${file.unicodeRange};`);
      }
      lines.push("}");
      blocks.push(lines.join("\n"));
    }
  }
  return `${blocks.join("\n\n")}\n`;
}
